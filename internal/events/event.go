// Package events defines the SadakWatch road-event domain model: the
// detection taxonomy, severities, raw road events (observations) and the
// aggregated defects that remediation is tracked against.
package events

import "time"

// EventType is a road-defect class from the detection taxonomy.
type EventType string

const (
	EventPothole        EventType = "pothole"
	EventRoadCrack      EventType = "road_crack"
	EventBrokenSurface  EventType = "broken_surface"
	EventWaterlogging   EventType = "waterlogging"
	EventDebris         EventType = "debris"
	EventRoadEdgeDamage EventType = "road_edge_damage"
	EventMissingMarking EventType = "missing_lane_marking"
	EventDamagedManhole EventType = "damaged_manhole"
	EventSpeedBreaker   EventType = "speed_breaker"
)

// EventTypes lists every supported event type in display order.
var EventTypes = []EventType{
	EventPothole, EventRoadCrack, EventBrokenSurface, EventWaterlogging, EventDebris,
	EventRoadEdgeDamage, EventMissingMarking, EventDamagedManhole, EventSpeedBreaker,
}

// Valid reports whether t belongs to the taxonomy.
func (t EventType) Valid() bool {
	for _, known := range EventTypes {
		if t == known {
			return true
		}
	}
	return false
}

// Severity is the assessed seriousness of a defect.
type Severity string

const (
	SeverityUnknown  Severity = "unknown"
	SeverityLow      Severity = "low"
	SeverityMedium   Severity = "medium"
	SeverityHigh     Severity = "high"
	SeverityCritical Severity = "critical"
)

// Rank orders severities so the worst observation of a defect can be kept.
// Unknown and invalid values rank lowest.
func (s Severity) Rank() int {
	switch s {
	case SeverityLow:
		return 1
	case SeverityMedium:
		return 2
	case SeverityHigh:
		return 3
	case SeverityCritical:
		return 4
	default:
		return 0
	}
}

// Valid reports whether s is a known severity.
func (s Severity) Valid() bool {
	return s == SeverityUnknown || s.Rank() > 0
}

// MaxSeverity returns the more severe of a and b.
func MaxSeverity(a, b Severity) Severity {
	if b.Rank() > a.Rank() {
		return b
	}
	if a == "" {
		return SeverityUnknown
	}
	return a
}

// Source identifies how an event was produced.
type Source string

const (
	SourceVision        Source = "vision"
	SourceAccelerometer Source = "accelerometer"
	SourceManual        Source = "manual"
)

// Valid reports whether s is a known source.
func (s Source) Valid() bool {
	return s == SourceVision || s == SourceAccelerometer || s == SourceManual
}

// RoadEvent is a single observation of a road defect produced by a vehicle.
// EventID is generated by the producer so uploads are idempotent across retries.
type RoadEvent struct {
	EventID        string    `json:"event_id"`
	VehicleID      string    `json:"vehicle_id"`
	EventType      EventType `json:"event_type"`
	Severity       Severity  `json:"severity"`
	Confidence     float64   `json:"confidence"`
	Latitude       float64   `json:"latitude"`
	Longitude      float64   `json:"longitude"`
	AccuracyM      float64   `json:"accuracy_m,omitempty"`
	DetectedAt     time.Time `json:"detected_at"`
	SpeedKPH       float64   `json:"speed_kph,omitempty"`
	HeadingDegrees float64   `json:"heading_degrees,omitempty"`
	Source         Source    `json:"source,omitempty"`
	ImageURI       string    `json:"image_uri,omitempty"`
	VideoURI       string    `json:"video_uri,omitempty"`

	// Set by the server during ingestion.
	DefectID   string    `json:"defect_id,omitempty"`
	RoadID     string    `json:"road_id,omitempty"`
	ReceivedAt time.Time `json:"received_at,omitempty"`
}

// Defect status values used for remediation tracking.
const (
	StatusOpen         = "open"
	StatusAcknowledged = "acknowledged"
	StatusInProgress   = "in_progress"
	StatusResolved     = "resolved"
	StatusRejected     = "rejected"
)

// Statuses lists every defect status.
var Statuses = []string{StatusOpen, StatusAcknowledged, StatusInProgress, StatusResolved, StatusRejected}

// ValidStatus reports whether s is a known defect status.
func ValidStatus(s string) bool {
	for _, known := range Statuses {
		if s == known {
			return true
		}
	}
	return false
}

// Closed reports whether a status ends a defect's active life. Detections near
// a closed defect start a new defect instead of being merged into it.
func Closed(status string) bool {
	return status == StatusResolved || status == StatusRejected
}

// Responsibility is who is answerable for a road location at a point in time.
type Responsibility struct {
	RoadID            string `json:"road_id,omitempty"`
	RoadName          string `json:"road_name,omitempty"`
	AuthorityID       string `json:"authority_id,omitempty"`
	AuthorityName     string `json:"authority_name,omitempty"`
	DivisionID        string `json:"division_id,omitempty"`
	DivisionName      string `json:"division_name,omitempty"`
	ContractID        string `json:"contract_id,omitempty"`
	ContractReference string `json:"contract_reference,omitempty"`
	ContractorID      string `json:"contractor_id,omitempty"`
	ContractorName    string `json:"contractor_name,omitempty"`
	OfficerID         string `json:"officer_id,omitempty"`
	OfficerName       string `json:"officer_name,omitempty"`
	OfficerTitle      string `json:"officer_designation,omitempty"`
	SourceReference   string `json:"source_reference,omitempty"`
}

// Defect is a persistent physical issue aggregated from one or more events.
type Defect struct {
	DefectID         string         `json:"defect_id"`
	EventType        EventType      `json:"event_type"`
	Severity         Severity       `json:"severity"`
	MaxConfidence    float64        `json:"max_confidence"`
	Latitude         float64        `json:"latitude"`
	Longitude        float64        `json:"longitude"`
	FirstSeen        time.Time      `json:"first_seen"`
	LastSeen         time.Time      `json:"last_seen"`
	ObservationCount int            `json:"observation_count"`
	VehicleCount     int            `json:"vehicle_count"`
	Status           string         `json:"status"`
	StatusUpdatedAt  time.Time      `json:"status_updated_at"`
	LatestImageURI   string         `json:"latest_image_uri,omitempty"`
	RecurrenceOf     string         `json:"recurrence_of,omitempty"`
	Responsibility   Responsibility `json:"responsibility"`
}

// StatusChange records one remediation transition of a defect.
type StatusChange struct {
	DefectID   string    `json:"defect_id"`
	FromStatus string    `json:"from_status"`
	ToStatus   string    `json:"to_status"`
	Note       string    `json:"note,omitempty"`
	Actor      string    `json:"actor,omitempty"`
	CreatedAt  time.Time `json:"created_at"`
}

// DefectDetail is a defect with its observations and remediation history.
type DefectDetail struct {
	Defect
	Observations []RoadEvent    `json:"observations"`
	History      []StatusChange `json:"history"`
}

// IngestResult describes what happened to one submitted event.
type IngestResult struct {
	EventID   string `json:"event_id"`
	DefectID  string `json:"defect_id,omitempty"`
	Duplicate bool   `json:"duplicate"`
	NewDefect bool   `json:"new_defect"`
	Error     string `json:"error,omitempty"`
}
